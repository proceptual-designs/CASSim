"""Build the installable, offline static site (FR-PWA-001 to FR-PWA-004).

    python -m tools.publish [--dist DIR] [--base-url CASSim] [--cdn]

Steps (decisions 0002, 0016, 0018): stage the app, `flet publish --no-cdn`, patch `index.html`,
vendor the Pyodide packages and the two PyPI wheels Flet installs at start-up, write the web
manifest and icons, and replace Flutter's self-unregistering service worker with a versioned
precaching one. `index.html` gets a loading screen and an "update available" bar.
"""

