FALLBACK_FONTS = ROOT / "tools" / "fallback_fonts"


def vendor_fallback_fonts(dist: Path) -> None:
    shutil.copytree(FALLBACK_FONTS, dist / "assets" / "fonts", dirs_exist_ok=True)


def write_engine_zip(dist: Path, bundle: Bundle) -> None:
    """`cassim.zip`: everything the engine worker imports (it boots its own Pyodide): the `cassim`
    package without the UI, and SymPy with mpmath."""
    lib = "/cassim_lib"  # where `ENGINE_JS` in cassim.app.web unpacks it
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        copy_cassim(root, dist, lib, bundle, ui=False)
        wheels = [pyodide_wheel(dist, name) for name in bundle.engine_packages]
        unpack_wheels(dist, wheels, root, lib)
        with zipfile.ZipFile(dist / "cassim.zip", "w", zipfile.ZIP_DEFLATED) as archive:
            for file in sorted(f for f in root.rglob("*") if f.is_file()):
                archive.write(file, file.relative_to(root).as_posix())


def draw_icon(size: int) -> PILImage:
    """The app icon, CASSim's own artwork: CAS over a blue SIM bar, in a rounded square."""
    from PIL import Image, ImageDraw, ImageFont

    def bold(px: float) -> FreeTypeFont | PILFont:
        try:
            return ImageFont.truetype("arialbd.ttf", int(px))
        except OSError:
            return ImageFont.load_default(int(px))

    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    draw.rounded_rectangle((0, 0, size - 1, size - 1), radius=size // 5, fill=THEME)
    draw.rounded_rectangle(
        (0, 0, size - 1, size - 1), radius=size // 6, outline=ACCENT, width=max(2, size // 32)
    )
    draw.text((size / 2, size * 0.36), "CAS", fill="#e8e8e8", font=bold(size * 0.36), anchor="mm")
    sim, gap = bold(size * 0.21), size * 0.015
    widths = [draw.textlength(c, font=sim) for c in "SIM"]
    text_w = sum(widths) + 2 * gap
    bar_w, bar_h, mid = text_w + size * 0.12, size * 0.26, size * 0.69
    draw.rounded_rectangle(
        (size / 2 - bar_w / 2, mid - bar_h / 2, size / 2 + bar_w / 2, mid + bar_h / 2),
        radius=size // 28,
        fill=ACCENT,
    )
    x = size / 2 - text_w / 2
    for letter, width in zip("SIM", widths, strict=True):
        draw.text((x, mid), letter, fill=THEME, font=sim, anchor="lm")
        x += width + gap
    return img


def write_icons(dist: Path) -> None:
    """App icons and the favicon (all the same artwork; no TI artwork)."""
    from PIL import Image

    out = dist / "icons"
    out.mkdir(exist_ok=True)
    draw_icon(192).save(out / "icon-192.png")
    draw_icon(512).save(out / "icon-512.png")
    # Maskable: the launcher crops to its own shape, so keep the artwork inside the safe zone.
    maskable = Image.new("RGBA", (512, 512), THEME)
    inner = draw_icon(512).resize((360, 360), Image.Resampling.LANCZOS)
    maskable.paste(inner, (76, 76), inner)
    maskable.save(out / "icon-maskable-512.png")
    draw_icon(64).save(dist / "favicon.png")  # Flet's index.html links this file


