def project_version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return data["project"]["version"]


def flet_version() -> str:
    import flet.version

    return flet.version.flet_version


def run(*cmd: str, cwd: Path = ROOT) -> None:
    done = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, check=False)
    if done.returncode:
        raise SystemExit(f"{' '.join(cmd)} failed:\n{done.stdout}\n{done.stderr}")


def copy_package(target: Path, bundle: Bundle, *, ui: bool) -> None:
    """Copy the `cassim` package into `target`: only the bundle's devices, with or without the
    Flet views, and its own `bundle.py`."""
    devices = ROOT / "src" / "cassim" / "devices"

    def ignore(folder: str, names: list[str]) -> set[str]:
        skip = {"__pycache__", "assets", *([] if ui else ["app", "ui"])}
        if Path(folder) == devices:  # the devices this bundle does not hold
            skip |= {n for n in names if (devices / n).is_dir() and n not in bundle.devices}
        return {n for n in names if n in skip or n.endswith(".pyc")}

    shutil.copytree(ROOT / "src" / "cassim", target / "cassim", ignore=ignore)
    (target / "cassim" / "bundle.py").write_text(
        BUNDLE_PY.format(name=bundle.name, devices=bundle.devices), encoding="utf-8"
    )


def stage(version: str, bundle: Bundle) -> None:
    """A throwaway app folder: main.py, the cassim package and a pyproject for Flet."""
    if STAGE.exists():
        shutil.rmtree(STAGE)
    (STAGE / "src").mkdir(parents=True)
    (STAGE / "src" / "main.py").write_text(MAIN_PY, encoding="utf-8")
    copy_package(STAGE / "src", bundle, ui=True)
    # Flet copies src/assets into the site root (decision 0016), so fonts/... is served at fonts/...
    shutil.copytree(ROOT / "src" / "cassim" / "app" / "assets", STAGE / "src" / "assets")
    (STAGE / "pyproject.toml").write_text(
        STAGE_PYPROJECT.format(version=version, flet=flet_version()), encoding="utf-8"
    )


def lock_file(dist: Path) -> dict[str, Any]:
    return json.loads((dist / "pyodide" / "pyodide-lock.json").read_text(encoding="utf-8"))


def pyodide_wheel(dist: Path, name: str) -> Path:
    """A package from Pyodide's own distribution, downloaded once into `WHEELS`."""
    file_name = lock_file(dist)["packages"][name]["file_name"]
    version = json.loads((dist / "pyodide" / "package.json").read_text(encoding="utf-8"))["version"]
    target = WHEELS / file_name
    if not target.exists():
        WHEELS.mkdir(parents=True, exist_ok=True)
        url = f"https://cdn.jsdelivr.net/pyodide/v{version}/full/{file_name}"
        target.write_bytes(urllib.request.urlopen(url).read())
    return target


def pypi_wheel(name: str, version: str) -> Path:
    """A pure-Python wheel from PyPI, downloaded once into `WHEELS`."""
    found = sorted(WHEELS.glob(f"{name}-{version}-*.whl"))
    if found:
        return found[0]
    WHEELS.mkdir(parents=True, exist_ok=True)
    meta = json.loads(urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json").read())
    wheel = next(u for u in meta["urls"] if u["packagetype"] == "bdist_wheel")
    target = WHEELS / wheel["filename"]
    target.write_bytes(urllib.request.urlopen(wheel["url"]).read())
    return target


def vendor_pyodide(dist: Path) -> None:
    """Copy the packages Pyodide loads at run time (`RUNTIME_PACKAGES`) into dist/pyodide."""
    for name in RUNTIME_PACKAGES:
        wheel = pyodide_wheel(dist, name)
        shutil.copyfile(wheel, dist / "pyodide" / wheel.name)


def same_python(dist: Path) -> bool:
    """Whether this Python writes bytecode that the site's Pyodide can load."""
    theirs = lock_file(dist)["info"]["python"].split(".")[:2]
    return theirs == [str(sys.version_info.major), str(sys.version_info.minor)]


def compile_tree(root: Path, runs_at: str, *, keep_source: bool) -> None:
    """Compile every module below `root`, so the browser does not have to at each start.

    Pyodide's file system is in memory, so nothing it compiles is kept: without this every start
    compiles every imported module again (SymPy alone is several seconds). `runs_at` is the folder
    the tree is unpacked to, for tracebacks. With `keep_source` the bytecode sits in `__pycache__`
    and is loaded unchecked; without it only the `.pyc` files are left, which halves the archive.
    """
    compileall.compile_dir(
        str(root),
        quiet=2,
        ddir=runs_at,
        legacy=not keep_source,
        invalidation_mode=py_compile.PycInvalidationMode.UNCHECKED_HASH,
        workers=0,
    )
    if not keep_source:
        for source in root.rglob("*.py"):
            if source.with_suffix(".pyc").exists():
                source.unlink()


def unpack_wheels(dist: Path, wheels: list[Path], target: Path, runs_at: str) -> None:
    """Unpack third-party wheels into `target`, as bytecode when this Python matches Pyodide's."""
    for wheel in wheels:
        with zipfile.ZipFile(wheel) as archive:
            archive.extractall(target)
    if same_python(dist):
        compile_tree(target, runs_at, keep_source=False)


def copy_cassim(target: Path, dist: Path, runs_at: str, bundle: Bundle, *, ui: bool) -> None:
    """Copy the bundle's `cassim` package (with or without the UI) into `target` and compile it."""
    copy_package(target, bundle, ui=ui)
    if same_python(dist):
        compile_tree(target / "cassim", f"{runs_at}/cassim", keep_source=True)


def write_app_archive(dist: Path, bundle: Bundle) -> None:
    """`app.tar.gz`, which Flet's worker unpacks and runs: `main.py`, the `cassim` package, and
    Flet with its two pure-Python dependencies in `__pypackages__` (decision 0027).

    `flet publish` writes an archive whose `requirements.txt` makes the worker load micropip and
    install the Flet wheel at every start. With the packages already inside, it does neither.
    """
    home = "/home/pyodide"  # where Pyodide starts, and so where the archive is unpacked
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        shutil.copyfile(STAGE / "src" / "main.py", root / "main.py")
        copy_cassim(root, dist, home, bundle, ui=True)
        wheels = [
            pypi_wheel("flet", flet_version()),
            pypi_wheel("repath", REPATH_VERSION),
            pyodide_wheel(dist, "six"),
        ]
        unpack_wheels(dist, wheels, root / "__pypackages__", f"{home}/__pypackages__")
        with tarfile.open(dist / "app.tar.gz", "w:gz") as archive:
            for file in sorted(f for f in root.rglob("*") if f.is_file()):
                archive.add(file, file.relative_to(root).as_posix())


# Fonts Flutter fetches for glyphs the bundled ones lack. They are committed under
