DEFAULT_DIST = ROOT / "build" / "web"
PYODIDE_PACKAGES = ["sympy", "pyyaml", "micropip", "msgpack", "six"]
APP_NAME = "CASSim"
THEME = "#1e1e1e"
DESCRIPTION = "A browser simulation of a CAS calculator for VCE mathematics."

