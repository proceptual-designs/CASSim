def patch_index(dist: Path, bundle: Bundle, *, cdn: bool) -> None:
    index = dist / "index.html"
    text = index.read_text(encoding="utf-8")
    if not cdn:
        text = text.replace(
            'pyodideUrl="pyodide/pyodide.mjs"', 'pyodideUrl="./pyodide/pyodide.mjs"'
        )
    # Flet's own metadata names the app "src"; the browser would use its manifest.json first.
    text = re.sub(r'<link rel="manifest" href="manifest\.json">\s*', "", text)
    text = re.sub(
        r"<title>.*?</title>", f"<title>{bundle.product}</title>", text, count=1, flags=re.S
    )
    text = re.sub(
        r'(<meta name="apple-mobile-web-app-title" content=")[^"]*"',
        rf'\g<1>{bundle.product}"',
        text,
    )
    text = re.sub(
        r'(<meta name="description" content=")[^"]*"', rf'\g<1>{DESCRIPTION}"', text, count=1
    )
    (dist / "manifest.json").unlink(missing_ok=True)
    text = re.sub(r"</head>", HEAD_TAGS + "\n</head>", text, count=1)
    text = re.sub(r"</body>", BODY_TAGS + "\n</body>", text, count=1)
    # Flutter's loader would register `flutter_service_worker.js?v=...` as well, which the browser
    # treats as a new version of ours; the registration in BODY_TAGS is the only one.
    bootstrap = dist / "flutter_bootstrap.js"
    boot = bootstrap.read_text(encoding="utf-8")
    boot, n = re.subn(r"serviceWorkerSettings:\s*\{.*?\},\s*", "", boot, count=1, flags=re.S)
    if n != 1:
        raise SystemExit("flutter_bootstrap.js has no serviceWorkerSettings block to remove")
    bootstrap.write_text(boot, encoding="utf-8")
    index.write_text(text, encoding="utf-8")


def content_hash(dist: Path) -> str:
    digest = hashlib.sha256()
    for f in sorted(dist.rglob("*")):
        if f.is_file() and f.name not in {
            "precache.json",
            "flutter_service_worker.js",
            "version.json",
        }:
            digest.update(f.relative_to(dist).as_posix().encode())
            digest.update(f.read_bytes())
    return digest.hexdigest()[:10]


def add_offline_cache(dist: Path, version: str) -> int:
    """Write `version.json`, `precache.json` and the service worker; return the file count."""
    build = f"{version}+{content_hash(dist)}"
    (dist / "version.json").write_text(json.dumps({"version": build}), encoding="utf-8")
    files = sorted(
        f.relative_to(dist).as_posix()
        for f in dist.rglob("*")
        if f.is_file() and f.suffix != ".map" and f.name != "precache.json"
    )
    (dist / "precache.json").write_text(json.dumps(["./", *files]), encoding="utf-8")
    (dist / "flutter_service_worker.js").write_text(
        SERVICE_WORKER.format(version=build), encoding="utf-8"
    )
    return len(files)


def tree_size(root: Path) -> float:
    return sum(f.stat().st_size for f in root.rglob("*") if f.is_file()) / 1e6


def size_report(dist: Path, bundle: Bundle) -> str:
    """What a first visit downloads, in MB: the whole site and its largest parts."""
    parts = {
        "app archive (Flet, the shell, the UI)": dist / "app.tar.gz",
        "engine archive (the devices' engines)": dist / "cassim.zip",
        "Pyodide": dist / "pyodide",
        "Flutter (main.dart.*, canvaskit)": None,
    }
    lines = [f"bundle {bundle.name} ({bundle.product}: {', '.join(bundle.devices)})"]
    flutter = sum(
        f.stat().st_size
        for f in dist.rglob("*")
        if f.is_file() and (f.name.startswith("main.dart") or "canvaskit" in f.parts)
    )
    for label, path in parts.items():
        if path is None:
            size = flutter / 1e6
        elif path.is_dir():
            size = tree_size(path)
        else:
            size = path.stat().st_size / 1e6 if path.exists() else 0.0
        lines.append(f"  {label:40} {size:6.1f} MB")
    lines.append(f"  {'whole site':40} {tree_size(dist):6.1f} MB")
    return "\n".join(lines)


def build(dist: Path, base_url: str, bundle: Bundle | None = None, *, cdn: bool = False) -> None:
    """Build `bundle` (default: `all`) into `dist`."""
    bundle = bundle or bundles()["all"]
    version = project_version()
    stage(version, bundle)
    if dist.exists():
        shutil.rmtree(dist)
    flet = Path(sys.executable).with_name("flet.exe" if sys.platform == "win32" else "flet")
    cmd = [str(flet), "publish", "src/main.py", "--distpath", str(dist)]
    if base_url:
        cmd += ["--base-url", base_url]
    if not cdn:
        cmd.append("--no-cdn")
    run(*cmd, cwd=STAGE)
    patch_index(dist, bundle, cdn=cdn)
    if not cdn:
        vendor_pyodide(dist)
        vendor_fallback_fonts(dist)
    write_app_archive(dist, bundle)
    write_engine_zip(dist, bundle)
    write_icons(dist)
    write_manifest(dist, bundle)
    count = add_offline_cache(dist, version)
    print(f"built {dist} : {count} precached files")
    print(size_report(dist, bundle))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    known = bundles()
    parser.add_argument("--bundle", choices=sorted(known), default="all")
    parser.add_argument("--dist", type=Path, default=DEFAULT_DIST)
    parser.add_argument(
        "--base-url",
        default="",
        help="sub-path on the host, for example CASSim; '' (default) for the root",
    )
    parser.add_argument("--cdn", action="store_true", help="leave Pyodide and CanvasKit on the CDN")
    args = parser.parse_args()
    build(args.dist.resolve(), args.base_url, known[args.bundle], cdn=args.cdn)


if __name__ == "__main__":
    main()
