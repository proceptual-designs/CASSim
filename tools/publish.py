SERVICE_WORKER = """// CASSim service worker (generated by tools/publish.py). Version {version}.
// Precache everything at install; serve same-origin GETs cache-first; fetch index.html
// network-first so a new version is noticed even though hosts cache for minutes.
const CACHE = "cassim-{version}";
self.addEventListener("install", (event) => {{
  event.waitUntil((async () => {{
    const list = await (await fetch("precache.json", {{cache: "no-store"}})).json();
    const cache = await caches.open(CACHE);
    await cache.addAll(list);
  }})());
}});
self.addEventListener("message", (event) => {{
  if (event.data === "skipWaiting") self.skipWaiting();
}});
self.addEventListener("activate", (event) => {{
  event.waitUntil((async () => {{
    for (const key of await caches.keys()) if (key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  }})());
}});
self.addEventListener("fetch", (event) => {{
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  const isPage = req.mode === "navigate";
  event.respondWith((async () => {{
    const cache = await caches.open(CACHE);
    if (isPage) {{
      try {{
        const res = await fetch(req, {{cache: "no-cache"}});
        if (res.ok) return res;
      }} catch (err) {{ /* offline: fall through to the cache */ }}
      return (await cache.match("index.html", {{ignoreSearch: true}})) || Response.error();
    }}
    const hit = await cache.match(req, {{ignoreSearch: true}});
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok) cache.put(req, res.clone());
    return res;
  }})());
}});
"""

