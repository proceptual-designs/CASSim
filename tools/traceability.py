"""Trace every SRS requirement ID to the tests that cite it (NFR-MAINT-006).

    python -m tools.traceability            # write docs/traceability.md
    python -m tools.traceability --check    # CI: fail if the file is stale or a gap has no reason

A requirement is *traced* when its ID appears in a file under `tests/` or `corpus/` (a docstring, a
comment, a marker or a corpus note). One that is not must have a line in
`docs/traceability-reasons.yaml` saying why, or `--check` fails. A reason for an ID that is traced,
or that is not in the SRS, also fails, so the file cannot go stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRS = ROOT / "docs" / "SRS.md"
REASONS = ROOT / "docs" / "traceability-reasons.yaml"
OUTPUT = ROOT / "docs" / "traceability.md"
SEARCH = (ROOT / "tests", ROOT / "corpus")
SUFFIXES = {".py", ".yaml", ".yml", ".md", ".js"}

ID = r"(?:N?FR|FID)-(?:[A-Z]+-)?\d+"
ROW = re.compile(rf"^\|\s*\*{{0,2}}({ID})\*{{0,2}}\s*\|.*\|\s*([MSCW])[^|]*\|[^|]*\|\s*$")
BULLET = re.compile(rf"^-\s+\*{{0,2}}({ID})\*{{0,2}}\s+\(([MSCW])")
MENTION = re.compile(ID)
PRIORITY = {"M": "Must", "S": "Should", "C": "Could", "W": "Would"}


@dataclass(frozen=True)
class Requirement:
    id: str
    priority: str
    section: str


def requirements(text: str) -> list[Requirement]:
    """The IDs the SRS defines (a table row or a bullet), with priority and section number."""
    found: dict[str, Requirement] = {}
    section = ""
    for line in text.splitlines():
        heading = re.match(r"^#{2,4}\s+(\d+(?:\.\d+)*)\.?\s", line)
        if heading:
            section = heading.group(1)
        match = ROW.match(line) or BULLET.match(line)
        if match and match.group(1) not in found:
            found[match.group(1)] = Requirement(match.group(1), match.group(2), section)
    return list(found.values())


def citations(roots: tuple[Path, ...] = SEARCH, base: Path = ROOT) -> dict[str, set[str]]:
    """Requirement ID -> the files under `roots` that mention it, as paths relative to `base`."""
    cited: dict[str, set[str]] = defaultdict(set)
    for root in roots:
        for path in sorted(root.rglob("*")):
            if path.suffix not in SUFFIXES or not path.is_file() or "__pycache__" in path.parts:
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
            for found in set(MENTION.findall(text)):
                cited[found].add(path.relative_to(base).as_posix())
    return cited


def load_reasons(path: Path = REASONS) -> dict[str, str]:
    data = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else None
    return {str(k): str(v) for k, v in (data or {}).items()}


def problems(
    reqs: list[Requirement], cited: dict[str, set[str]], reasons: dict[str, str]
) -> list[str]:
    ids = {r.id for r in reqs}
    out = [
        f"{r.id}: not cited by any test and has no reason"
        for r in reqs
        if r.id not in cited and r.id not in reasons
    ]
    out += [f"{i}: has a reason but is not in the SRS" for i in sorted(reasons) if i not in ids]
    out += [
        f"{i}: has a reason but a test now cites it; delete the reason"
        for i in sorted(reasons)
        if i in ids and i in cited
    ]
    return out


def render(reqs: list[Requirement], cited: dict[str, set[str]], reasons: dict[str, str]) -> str:
    traced = [r for r in reqs if r.id in cited]
    gaps = [r for r in reqs if r.id not in cited]
    lines = [
        "# Traceability",
        "",
        "Generated by `python -m tools.traceability` from `docs/SRS.md`, `tests/` and `corpus/`.",
        "Do not edit; change the tests or `docs/traceability-reasons.yaml` and regenerate.",
        "CI runs `--check` (NFR-MAINT-006).",
        "",
        f"**{len(reqs)}** requirements: **{len(traced)}** cited by a test or corpus file, "
        f"**{len(gaps)}** not.",
        "",
        "| Priority | Requirements | Cited | Not cited |",
        "|---|---|---|---|",
    ]
    for code, name in PRIORITY.items():
        group = [r for r in reqs if r.priority == code]
        done = sum(1 for r in group if r.id in cited)
        lines.append(f"| {name} | {len(group)} | {done} | {len(group) - done} |")
    lines += ["", "## Not cited by any test", "", "| ID | Priority | Reason |", "|---|---|---|"]
    for r in gaps:
        reason = reasons.get(r.id, "**none recorded**").replace("|", "/")
        lines.append(f"| {r.id} | {PRIORITY[r.priority]} | {reason} |")
    lines += ["", "## Cited", "", "| ID | Priority | Files |", "|---|---|---|"]
    for r in traced:
        files = sorted(cited[r.id])
        shown = ", ".join(f"`{f}`" for f in files[:3])
        more = f" and {len(files) - 3} more" if len(files) > 3 else ""
        lines.append(f"| {r.id} | {PRIORITY[r.priority]} | {shown}{more} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify, do not write")
    args = parser.parse_args()
    reqs = requirements(SRS.read_text(encoding="utf-8"))
    cited = citations()
    reasons = load_reasons()
    issues = problems(reqs, cited, reasons)
    text = render(reqs, cited, reasons)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            issues.append("docs/traceability.md is out of date: run python -m tools.traceability")
        for issue in issues:
            print(issue, file=sys.stderr)
        return 1 if issues else 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    for issue in issues:
        print(issue, file=sys.stderr)
    print(f"{len(reqs)} requirements, {sum(1 for r in reqs if r.id not in cited)} not cited")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
