"""The built-in function names, for code that must not import the catalog.

The catalog registers its functions on import and that loads SymPy. In the browser the UI's worker
never does (decision 0027), but the editor still needs to know that `sin` is a function. The set
below is generated: run `python -m tools.builtin_names` after adding or removing a function
(`tests/unit/test_builtin_names.py` fails until you do).
"""

import re

# `sin⁻¹` and `arcsin` are one function; the catalog knows it by the typed name.
_INVERSE_SPELLING = re.compile(r"(sin|cos|tan|sec|csc|cot)(h?)⁻¹")


def canonical(name: str) -> str:
    """The key the catalog files a function under."""
    return _INVERSE_SPELLING.sub(r"arc\1\2", name.casefold())


def is_builtin(name: str) -> bool:
    return canonical(name) in NAMES


